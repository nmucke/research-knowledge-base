def test_symlinked_roots_registry_and_cache_are_rejected(
    tmp_path: Path,
) -> None:
    _registry(tmp_path)
    outside = tmp_path.parent / f"{tmp_path.name}-outside"
    outside.mkdir()
    outside_store = MarkdownStore(outside)
    outside_store.create(_note())
    papers = tmp_path / "vault" / "Literature" / "Papers"
    papers.parent.mkdir(parents=True, exist_ok=True)
    try:
        papers.symlink_to(outside, target_is_directory=True)
    except OSError as error:  # pragma: no cover - platform permission boundary
        pytest.skip(f"symlinks unavailable: {error}")

    unsafe_root = ValidationService(_settings(tmp_path), _store(tmp_path)).run()

    assert _codes(unsafe_root) == {"papers-directory-unsafe"}

    papers.unlink()
    store = _store(tmp_path)
    path = store.create(_reviewed_note())
    _add_review(store, path)
    registry = tmp_path / "vault" / "System" / "tag-registry.md"
    registry.unlink()
    external_registry = outside / "tag-registry.md"
    external_registry.write_text(
        "### `domain/weather`\n\nWeather.\n", encoding="utf-8"
    )
    registry.symlink_to(external_registry)
    cache = tmp_path / ".research" / "paper-text" / "doeUseful2026.md"
    cache.parent.mkdir(parents=True)
    cache.symlink_to(external_registry)

    unsafe_files = ValidationService(_settings(tmp_path), store).run()

    assert {"tag-registry-invalid", "extraction-cache-unsafe"} <= _codes(unsafe_files)


def test_extraction_cache_rejects_duplicate_fields_bad_pages_and_empty_text(
    tmp_path: Path,
) -> None:
    _registry(tmp_path)
    store = _store(tmp_path)
    path = store.create(_reviewed_note())
    _add_review(store, path)
    cache = _cache(tmp_path)
    contents = cache.read_text(encoding="utf-8")
    cache.write_text(
        contents.replace(
            "attachment_key: PDFX5678\n",
            "attachment_key: WRONG123\nattachment_key: PDFX5678\n",
        ),
        encoding="utf-8",
    )

    duplicate = ValidationService(_settings(tmp_path), store).run()

    assert "extraction-cache-invalid" in _codes(duplicate)

    _cache(tmp_path)
    contents = cache.read_text(encoding="utf-8")
    closing = contents.find("\n---\n", 4)
    cache.write_text(
        f"{contents[: closing + 5]}\n<!-- PAGE 2 -->\n",
        encoding="utf-8",
    )

    malformed_body = ValidationService(_settings(tmp_path), store).run()

    assert {"extraction-cache-pages-invalid", "extraction-cache-empty"} <= _codes(
        malformed_body
    )
