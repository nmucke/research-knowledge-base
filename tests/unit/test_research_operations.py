def test_full_text_provenance_checks_only_local_cache_and_detects_cache_change(
    tmp_path: Path,
) -> None:
    operations, store = _operations(tmp_path)
    paper = store.note_path("doe2026")
    store.update_zotero_fields(paper, {"pdf_attachment_key": "PDFX5678"})
    cache = operations.settings.paper_text_dir / "doe2026.md"
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(
        "---\ncitekey: doe2026\nzotero_key: ABCD1234\nattachment_key: PDFX5678\n"
        "source_mtime: 1.0\nsource_size: 100\n"
        "extracted_at: 2026-09-14T12:00:00+00:00\nextractor: pymupdf\n"
        "extractor_version: test\npages: 1\nfailed_pages: []\n---\n\n"
        "<!-- PAGE 1 -->\n\nSynthetic full text.\n",
        encoding="utf-8",
    )

    class LocalContext:
        def review_context(self, citekey: str, *, scope: str) -> ReviewContext:
            assert citekey == "doe2026"
            return ReviewContext(
                paper_note=paper,
                extracted_paper=cache,
                reading_profile=operations.settings.reading_profile_path,
                tag_registry=operations.settings.tag_registry_path,
                scope="full-text",
            )

    full_operations = ResearchOperations(
        operations.settings,
        store,
        extraction=LocalContext(),  # type: ignore[arg-type]
    )
    _context, session = full_operations.start_review("doe2026", scope="full-text")
    submission = _review(session.session_id, session.expected_revision).model_copy(
        update={
            "review_scope": "full-text",
            "managed_review": _review(
                session.session_id, session.expected_revision
            ).managed_review.replace("Scope:** abstract-only", "Scope:** full-text"),
        }
    )
    full_operations.submit_review(submission)
    fresh = full_operations.review_provenance_status("doe2026")
    assert fresh is not None and not fresh.stale
    assert fresh.source_check == "local-cache"
    assert "Zotero PDF" in fresh.source_limitation

    cache.write_text(cache.read_text(encoding="utf-8") + "Changed cache.\n", encoding="utf-8")
    stale = full_operations.review_provenance_status("doe2026")
    assert stale is not None
    assert stale.stale_reasons == ("source-changed",)


