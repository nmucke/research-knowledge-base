def test_catalog_state_rejects_symlinked_ancestor(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (tmp_path / ".research").symlink_to(outside, target_is_directory=True)
    settings = Settings(_env_file=None, research_vault_path=tmp_path)

    with pytest.raises(ValidationError, match="symlinked catalog path"):
        CatalogOperations(settings)


def test_reject_persists_status_and_clears_pending_mirror(tmp_path: Path) -> None:
    operations, approval, _store = _operations(tmp_path)
    proposal = operations.propose(_create_request())

    approval.reject(proposal.proposal_id)

    assert operations._load(proposal.proposal_id).status == "rejected"
    mirror = tmp_path / f"vault/System/Proposals/{proposal.proposal_id}.md"
    text = mirror.read_text(encoding="utf-8")
    assert "status: rejected" in text
    assert "pending_count: 0" in text
    with pytest.raises(ValidationError, match="already rejected"):
        approval.apply(proposal.proposal_id)


def test_custom_obsidian_directory_stages_project_index_safely(tmp_path: Path) -> None:
    notes = tmp_path / "notes"
    (notes / "System").mkdir(parents=True)
    (notes / "Projects").mkdir(parents=True)
    (notes / "Literature/Papers").mkdir(parents=True)
    (notes / "System/tag-registry.md").write_text(REGISTRY, encoding="utf-8")
