def _operations(tmp_path: Path) -> tuple[ResearchOperations, MarkdownStore]:
    settings = Settings(_env_file=None, research_vault_path=tmp_path)  # type: ignore[call-arg]
    settings.reading_profile_path.parent.mkdir(parents=True, exist_ok=True)
    settings.reading_profile_path.write_text("# Profile\n", encoding="utf-8")
    settings.tag_registry_path.write_text(
        "# Tags\n\n### `domain/weather`\n\nWeather research.\n", encoding="utf-8"
    )
    settings.projects_dir.mkdir(parents=True, exist_ok=True)
    store = MarkdownStore(settings.papers_dir)
    store.create(
        PaperNote(
            zotero_key="ABCD1234",
            citekey="doe2026",
            title="Weather",
            abstract="An abstract.",
        )
    )
    return ResearchOperations(settings, store), store


def _review(session_id: str, revision: str) -> ReviewSubmission:
    block = (
        "> **Generated by:** Codex\n> **Model:** test\n> **Date:** 2026-09-14\n"
        "> **Scope:** abstract-only\n> **Coverage:** complete\n"
        "> **Human verified:** No\n\n### Summary\n\n- A result.\n\n"
        "### Main contribution\n\nA contribution.\n\n### Main limitations\n\n"
        "- Abstract evidence only.\n\n### Reading recommendation\n\n"
        "**Read.** Relevant.\n\n### Tags\n\n"
        "**Applied:** `domain/weather`\n**Suggested:** none"
    )
    return ReviewSubmission(
        session_id=session_id,
        citekey="doe2026",
        expected_revision=revision,
        review_scope="abstract-only",
        review_coverage="complete",
        agent="Codex",
        model="test",
        review_date=date(2026, 9, 14),
        recommendation="read",
        recommendation_reason="Relevant.",
        recommendation_confidence="medium",
        applied_tags=("domain/weather",),
        managed_review=block,
    )


def test_abstract_review_is_one_validated_revision_checked_write(tmp_path: Path) -> None:
    operations, store = _operations(tmp_path)
    context, session = operations.start_review("doe2026", scope="auto")
    assert context.scope == "abstract-only"
    assert context.extracted_paper is None

    receipt = operations.submit_review(_review(session.session_id, session.expected_revision))
    note = store.parse(store.note_path("doe2026")).note
    assert note.ai_review_status == "reviewed"
    assert note.human_read_status == "unread"
    assert receipt.proposal_id
    assert receipt.revision == store.revision(store.note_path("doe2026"))
    assert not (operations._sessions / f"{session.session_id}.json").exists()
    assert (operations._history / f"review-{session.session_id}.json").is_file()

    status = operations.review_provenance_status("doe2026")
    assert status is not None
    assert not status.stale
    operations.settings.reading_profile_path.write_text("# Changed profile\n", encoding="utf-8")
    changed = operations.review_provenance_status("doe2026")
    assert changed is not None
    assert changed.stale
    assert changed.stale_reasons == ("reading-profile-changed",)


