def test_verified_review_cannot_be_replaced_by_agent_submission(tmp_path: Path) -> None:
    _workspace_root, settings, store = _workspace(tmp_path)
    path = store.note_path("boundary2026")
    text = path.read_text(encoding="utf-8")
    path.write_text(
        text.replace("ai_review_human_verified: false", "ai_review_human_verified: true")
    )
    api = ResearchAPI(settings)
    context = api.call("context", {"citekey": "boundary2026", "scope": "abstract-only"})
    before = path.read_bytes()
    session = context["session"]
    block = (
        "> **Generated by:** test\n> **Model:** test\n> **Date:** 2026-09-14\n"
        "> **Scope:** abstract-only\n> **Coverage:** complete\n> **Human verified:** No\n\n"
        "### Summary\n\n- Synthetic.\n\n### Main contribution\n\nSynthetic.\n\n"
        "### Main limitations\n\n- Abstract only.\n\n### Reading recommendation\n\n"
        "**Read.** Synthetic.\n\n### Tags\n\n**Applied:** none\n**Suggested:** none"
    )
    submission = ReviewSubmission(
        session_id=session["session_id"],
        citekey="boundary2026",
        expected_revision=session["expected_revision"],
        review_scope="abstract-only",
        review_coverage="complete",
        agent="test",
        model="test",
        review_date=date(2026, 9, 14),
        recommendation="read",
        recommendation_reason="Synthetic.",
        recommendation_confidence="low",
        managed_review=block,
    )

    with pytest.raises(ValidationError, match="human-verified"):
        api.operations.submit_review(submission)
    assert path.read_bytes() == before


