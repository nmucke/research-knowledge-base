from pathlib import Path

import yaml  # type: ignore[import-untyped]

from research_kb.models import PaperNote

ROOT = Path(__file__).parents[2]
VAULT = ROOT / "Vault"
AGENT_FILES = (VAULT / "AGENTS.md", VAULT / "CLAUDE.md")
TEMPLATE = VAULT / "System" / "Templates" / "Paper.md"


def _frontmatter(text: str) -> dict[str, object]:
    _, raw, _ = text.split("---", maxsplit=2)
    parsed = yaml.safe_load(raw)
    assert isinstance(parsed, dict)
    return parsed


def test_agent_instructions_are_equivalent_and_executable() -> None:
    instructions = tuple(path.read_text(encoding="utf-8") for path in AGENT_FILES)

    assert instructions[0] == instructions[1]
    contract = instructions[0]
    assert contract.index("uv run research review-context <citekey>") < contract.index(
        "uv run research validate <citekey>"
    )
    assert "not expected to be on the shell's `PATH`" in contract
    assert "do not probe for or invoke a bare `research` executable first" in contract
    assert ".venv/bin/research ..." in contract
    for required_input in (
        "paper note",
        "extracted paper text",
        "System/reading-profile.md",
        "System/tag-registry.md",
    ):
        assert required_input in contract

    for provenance_label in (
        "**Generated by:**",
        "**Model:**",
        "**Date:**",
        "**Scope:**",
        "**Coverage:**",
        "**Human verified:** No",
    ):
        assert provenance_label in contract
    for review_heading in (
        "### Summary",
        "### Main contribution",
        "### Main limitations",
        "### Reading recommendation",
        "### Tags",
    ):
        assert review_heading in contract
    assert "**Applied:**" in contract
    assert "**Suggested:**" in contract


