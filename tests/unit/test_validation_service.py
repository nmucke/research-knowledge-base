def test_agent_workflow_baseline_detects_changes_to_every_human_owned_field(
    tmp_path: Path,
) -> None:
    _registry(tmp_path)
    store = _store(tmp_path)
    before = _note()
    path = store.create(before)
    service = ValidationService(_settings(tmp_path), store)
    snapshot_path = service.capture_workflow_snapshot("doeUseful2026")
    contents = path.read_text(encoding="utf-8")
    contents = contents.replace("human_read_status: unread", "human_read_status: read")
    contents = contents.replace("human_read_date: null", "human_read_date: '2026-08-06'")
    contents = contents.replace("human_rating: null", "human_rating: 5")
    contents = contents.replace("human_priority: null", "human_priority: 4")
    contents = contents.replace("human_relevance: null", "human_relevance: 3")
    contents = contents.replace("## Human notes\n", "## Human notes\nAgent changed this.\n")
    path.write_text(contents, encoding="utf-8")

    report = service.run("doeUseful2026")

    ownership = [issue for issue in report.issues if issue.code == "human-field-changed"]
    assert len(ownership) == 5
    assert any("must never infer" in issue.message for issue in ownership)
    assert "human-notes-changed" in _codes(report)
    assert snapshot_path.exists()


