class _LocalZotero:
    paths: dict[str, Path] = {}

    def __init__(self, *_args: object, **_kwargs: object) -> None:
        pass

    def __enter__(self) -> _LocalZotero:
        return self

    def __exit__(self, *_args: object) -> None:
        pass

    def resolve_attachment_path(self, attachment_key: str, **_kwargs: object) -> Path:
        return self.paths[attachment_key]


def _pdf(path: Path, pages: tuple[str, ...]) -> None:
    document = pymupdf.open()
    for text in pages:
        page = document.new_page()
        if text:
            page.insert_textbox((72, 72, 520, 760), text)
    document.save(path)
    document.close()


def _review_payload(session: dict[str, Any], scope: str) -> dict[str, object]:
    coverage = "complete" if scope == "full-text" else "partial"
    block = (
        "> **Generated by:** test\n> **Model:** test\n> **Date:** 2026-09-14\n"
        f"> **Scope:** {scope}\n> **Coverage:** {coverage}\n> **Human verified:** No\n\n"
        "### Summary\n\n- Synthetic result.\n\n### Main contribution\n\nSynthetic.\n\n"
        "### Main limitations\n\n- Synthetic evidence.\n\n### Reading recommendation\n\n"
        "**Read.** Synthetic.\n\n### Tags\n\n**Applied:** none\n**Suggested:** none"
    )
    return {
        "session_id": session["session_id"],
        "citekey": "pdf2026",
        "expected_revision": session["expected_revision"],
        "review_scope": scope,
        "review_coverage": coverage,
        "agent": "test",
        "model": "test",
        "review_date": "2026-09-14",
        "recommendation": "read",
        "recommendation_reason": "Synthetic.",
        "recommendation_confidence": "low",
        "managed_review": block,
    }


def _workspace(tmp_path: Path) -> tuple[Path, Settings, MarkdownStore]:
    workspace = tmp_path / "workspace"
    shutil.copytree(ASSETS, workspace / "vault")
    settings = Settings(_env_file=None, research_vault_path=workspace)  # type: ignore[call-arg]
    store = MarkdownStore(settings.papers_dir)
    store.create(
        PaperNote(
            zotero_key="BOUND001",
            citekey="boundary2026",
            title="Boundary Study",
            abstract="Synthetic abstract.",
        )
    )
    return workspace, settings, store


def test_project_identifier_cannot_traverse_workspace(tmp_path: Path) -> None:
    _workspace_root, settings, _store = _workspace(tmp_path)
    api = ResearchAPI(settings)

    with pytest.raises(ModelValidationError):
        api.call("projects", {"project_id": "../../outside"})
    with pytest.raises(ModelValidationError):
        api.call("projects", {"project_id": "/absolute"})
    with pytest.raises((ModelValidationError, ValidationError, ValueError)):
        api.call(
            "catalog-propose",
            {
                "request": {
                    "operation": "project-create",
                    "project_id": "../../outside",
                    "title": "Traversal",
                    "description": "Synthetic.",
                    "goals": ["Test boundaries."],
                    "scope_in": ["Synthetic data."],
                    "scope_out": ["Private data."],
                    "rationale": "Boundary test.",
                }
            },
        )


def test_extraction_cache_cannot_escape_through_symlinked_ancestor(tmp_path: Path) -> None:
    workspace, settings, _store = _workspace(tmp_path)
    outside = tmp_path / "outside-cache"
    outside.mkdir()
    settings.paper_text_dir.parent.mkdir(parents=True, exist_ok=True)
    settings.paper_text_dir.symlink_to(outside, target_is_directory=True)

    with pytest.raises(ValueError, match="symlink|outside"):
        ResearchAPI(settings).call("text", {"citekey": "boundary2026"})
    assert not tuple(outside.iterdir())
    assert workspace.is_dir()


