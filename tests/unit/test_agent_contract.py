def test_paper_template_has_current_schema_defaults_and_managed_blocks() -> None:
    text = TEMPLATE.read_text(encoding="utf-8")
    metadata = _frontmatter(text)

    assert set(metadata) == set(PaperNote.model_fields)
    PaperNote.model_validate(metadata)
    assert metadata["schema_version"] == 1
    assert metadata["type"] == "paper"
    assert metadata["human_read_status"] == "unread"
    assert metadata["ai_review_status"] == "not-reviewed"
    assert metadata["ai_review_version"] == 0
    assert metadata["ai_review_human_verified"] is False
    assert metadata["tags"] == []
    assert metadata["ai_applied_tags"] == []
    assert metadata["ai_suggested_tags"] == []
    assert metadata["zotero_missing"] is False

    for block in ("AI_REVIEW", "ZOTERO_ANNOTATIONS"):
        begin = f"<!-- BEGIN MANAGED:{block} -->"
        end = f"<!-- END MANAGED:{block} -->"
        assert text.count(begin) == 1
        assert text.count(end) == 1
        assert text.index(begin) < text.index(end)
    assert "No AI review has been generated." in text
    assert "No Zotero annotations have been imported." in text


def test_paper_template_keeps_human_and_ai_sections_separate() -> None:
    text = TEMPLATE.read_text(encoding="utf-8")

    human_start = text.index("## Human notes")
    ai_start = text.index("## AI review")
    human_section = text[human_start:ai_start]
    assert "MANAGED:" not in human_section
    for heading in ("### Summary", "### Important results", "### Critique", "### Connections"):
        assert heading in human_section


def test_root_agent_instructions_are_symlinks_into_the_vault() -> None:
    """Agents load instructions from the repository root; the vault owns the content."""
    for name in ("AGENTS.md", "CLAUDE.md"):
        link = ROOT / name
        assert link.is_symlink(), f"{name} must be a symlink so the vault holds the real file"
        assert link.resolve() == (VAULT / name).resolve()
        assert link.read_text(encoding="utf-8") == (VAULT / name).read_text(encoding="utf-8")
