@pytest.mark.parametrize(
    ("pages", "expected_scope"),
    [
        (("Full synthetic evidence. " * 50, "Second evidence page. " * 50), "full-text"),
        (("Partial synthetic evidence. " * 50, ""), "partial-text"),
    ],
)
def test_pdf_context_can_be_submitted_through_agent_api(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    pages: tuple[str, ...],
    expected_scope: str,
) -> None:
    _workspace_root, settings, store = _workspace(tmp_path)
    original = store.note_path("boundary2026")
    original.unlink()
    store.create(
        PaperNote(
            zotero_key="PDFP0001",
            citekey="pdf2026",
            title="Synthetic PDF Study",
            abstract="Synthetic abstract.",
            pdf_attachment_key="PDFX0001",
        )
    )
    pdf = tmp_path / f"{expected_scope}.pdf"
    _pdf(pdf, pages)
    _LocalZotero.paths = {"PDFX0001": pdf}
    monkeypatch.setattr("research_kb.agent_api.ZoteroClient", _LocalZotero)

    api = ResearchAPI(settings)
    context = api.call("context", {"citekey": "pdf2026", "scope": "full-text"})
    assert context["scope"] == expected_scope

    receipt = api.call("submit-review", _review_payload(context["session"], expected_scope))

    note = store.parse(store.note_path("pdf2026")).note
    assert receipt["review_version"] == 1
    assert note.ai_review_status == "reviewed"
    assert note.ai_review_scope == expected_scope


def test_pdf_source_changed_after_context_refuses_api_submission(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _workspace_root, settings, store = _workspace(tmp_path)
    store.note_path("boundary2026").unlink()
    store.create(
        PaperNote(
            zotero_key="PDFP0001",
            citekey="pdf2026",
            title="Synthetic PDF Study",
            abstract="Synthetic abstract.",
            pdf_attachment_key="PDFX0001",
        )
    )
    pdf = tmp_path / "changing.pdf"
    _pdf(pdf, ("Original full evidence. " * 60,))
    _LocalZotero.paths = {"PDFX0001": pdf}
    monkeypatch.setattr("research_kb.agent_api.ZoteroClient", _LocalZotero)
    api = ResearchAPI(settings)
    context = api.call("context", {"citekey": "pdf2026", "scope": "full-text"})
    before = store.note_path("pdf2026").read_bytes()
    pdf.unlink()
    _pdf(pdf, ("Replacement evidence is materially different. " * 80,))

    with pytest.raises(ValidationError, match="inputs changed"):
        api.call("submit-review", _review_payload(context["session"], "full-text"))
    assert store.note_path("pdf2026").read_bytes() == before
