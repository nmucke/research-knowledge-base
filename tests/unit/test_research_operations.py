def test_review_transaction_failure_restores_every_artifact(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    operations, store = _operations(tmp_path)
    _context, session = operations.start_review("doe2026")
    paper = store.note_path("doe2026")
    session_path = operations._sessions / f"{session.session_id}.json"
    before_paper = paper.read_bytes()
    before_session = session_path.read_bytes()
    import research_kb.operation_transaction as transaction_module

    real_commit = transaction_module._commit
    calls = 0

    def fail_second(path: Path, content: str | None, expected: str | None) -> None:
        nonlocal calls
        calls += 1
        if calls == 2:
            raise OSError("injected review write failure")
        real_commit(path, content, expected)

    monkeypatch.setattr(transaction_module, "_commit", fail_second)
    with pytest.raises(OSError, match="injected review write failure"):
        operations.submit_review(_review(session.session_id, session.expected_revision))

    assert paper.read_bytes() == before_paper
    assert session_path.read_bytes() == before_session
    assert not tuple(operations._proposals.glob("*.json"))
    assert not tuple((operations.settings.obsidian_vault_path / "System/Proposals").glob("*.md"))
    assert not tuple(operations._history.glob("review-*.json"))


def test_approval_requires_an_explicit_decision_for_every_item(tmp_path: Path) -> None:
    operations, store = _operations(tmp_path)
    _context, session = operations.start_review("doe2026")
    receipt = operations.submit_review(_review(session.session_id, session.expected_revision))
    assert receipt.proposal_id is not None
    approval = CurationApprovalService(operations)

    with pytest.raises(ValidationError, match="every proposal item"):
        approval.apply(
            ApprovedCurationRequest(
                proposal_id=receipt.proposal_id,
                decisions=(),
                expected_revision=receipt.revision,
            )
        )

    result = approval.apply(
        ApprovedCurationRequest(
            proposal_id=receipt.proposal_id,
            decisions=(CurationDecision(item_id="tag-existing-1", decision="accepted"),),
            expected_revision=receipt.revision,
        )
    )
    assert store.parse(store.note_path("doe2026")).note.tags == ("domain/weather",)
    assert result.kind == "curation-approval"


def test_project_approval_stages_and_updates_both_derived_blocks(tmp_path: Path) -> None:
    operations, store = _operations(tmp_path)
    project = operations.settings.projects_dir / "weather-project.md"
    project.write_text(
        "---\nschema_version: 1\ntype: project\nproject_id: weather-project\n"
        "title: Weather project\nstatus: active\nstarted:\ntarget:\ntags: []\n---\n\n"
        "# Weather project\n\n## Description\n\nSynthetic.\n\n## Related papers\n\n"
        "<!-- BEGIN MANAGED:PROJECT_PAPERS -->\n\nNo papers are linked to this project.\n\n"
        "<!-- END MANAGED:PROJECT_PAPERS -->\n\n## Notes\n",
        encoding="utf-8",
    )
    snapshot = operations.validator.capture_workflow_snapshot("doe2026")
    revision = store.revision(store.note_path("doe2026"))
    proposal = operations.propose_curation(
        CurationProposalRequest(
            citekey="doe2026",
            expected_revision=revision,
            items=(
                CurationItem(
                    item_id="project-1",
                    kind="project-link",
                    value="weather-project",
                    rationale="Matches the project scope.",
                ),
            ),
        )
    )
    approval = CurationApprovalService(operations)
    request = ApprovedCurationRequest(
        proposal_id=proposal.proposal_id,
        decisions=(CurationDecision(item_id="project-1", decision="accepted"),),
        expected_revision=revision,
    )
    preview = approval.preview(request)
    assert {item.path for item in preview} >= {
        "vault/Literature/Papers/doe2026.md",
        "vault/Projects/weather-project.md",
    }
    receipt = approval.apply(request)
    assert not snapshot.exists()
    assert "[[weather-project]]" in store.note_path("doe2026").read_text(encoding="utf-8")
    assert "[[doe2026]]" in project.read_text(encoding="utf-8")
    approval.undo(receipt.operation_id, receipt.revisions)
    assert snapshot.exists()
    assert "[[weather-project]]" not in store.note_path("doe2026").read_text(encoding="utf-8")
    assert "[[doe2026]]" not in project.read_text(encoding="utf-8")
    proposal_path = operations._proposals / f"{proposal.proposal_id}.json"
    assert json.loads(proposal_path.read_text(encoding="utf-8"))["status"] == "pending"


def test_review_persists_project_goal_rationale_in_proposal(tmp_path: Path) -> None:
    operations, _store = _operations(tmp_path)
    project = operations.settings.projects_dir / "weather-project.md"
    project.write_text(
        "---\nschema_version: 1\ntype: project\nproject_id: weather-project\n"
        "title: Weather project\nstatus: active\nstarted:\ntarget:\ntags: []\n---\n\n"
        "# Weather project\n\n## Description\n\nSynthetic.\n\n## Related papers\n\n"
        "<!-- BEGIN MANAGED:PROJECT_PAPERS -->\n\nNo papers are linked to this project.\n\n"
        "<!-- END MANAGED:PROJECT_PAPERS -->\n\n## Notes\n",
        encoding="utf-8",
    )
    _context, session = operations.start_review("doe2026")
    base = _review(session.session_id, session.expected_revision)
    rationale = "Directly evaluates the project's forecast-transfer goal."
    submission = base.model_copy(
        update={
            "suggested_projects": ("weather-project",),
            "suggested_project_rationales": {"weather-project": rationale},
            "managed_review": base.managed_review
            + "\n\n### Projects\n\n**Relevant:** `weather-project`\n**Considered:** none",
        }
    )
    receipt = operations.submit_review(submission)
    assert receipt.proposal_id is not None
    proposal = operations._load_proposal(receipt.proposal_id)
    project_item = next(item for item in proposal.items if item.kind == "project-link")
    assert project_item.rationale == rationale


def test_unknown_project_approval_fails_before_any_vault_change(tmp_path: Path) -> None:
    operations, store = _operations(tmp_path)
    paper = store.note_path("doe2026")
    revision = store.revision(paper)
    proposal = operations.propose_curation(
        CurationProposalRequest(
            citekey="doe2026",
            expected_revision=revision,
            items=(
                CurationItem(
                    item_id="project-1",
                    kind="project-link",
                    value="missing-project",
                    rationale="Synthetic invalid proposal.",
                ),
            ),
        )
    )
    before = {
        path: path.read_bytes()
        for path in operations.settings.obsidian_vault_path.rglob("*")
        if path.is_file()
    }
    with pytest.raises(ValidationError, match="unknown"):
        CurationApprovalService(operations).apply(
            ApprovedCurationRequest(
                proposal_id=proposal.proposal_id,
                decisions=(CurationDecision(item_id="project-1", decision="accepted"),),
                expected_revision=revision,
            )
        )
    assert all(path.read_bytes() == content for path, content in before.items())


def test_edit_during_staging_causes_conflict_and_preserves_external_edit(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    operations, store = _operations(tmp_path)
    project = operations.settings.projects_dir / "weather-project.md"
    project.write_text(
        "---\nschema_version: 1\ntype: project\nproject_id: weather-project\n"
        "title: Weather\nstatus: active\nstarted:\ntarget:\ntags: []\n---\n\n"
        "# Weather\n\n## Description\n\nSynthetic.\n\n## Related papers\n\n"
        "<!-- BEGIN MANAGED:PROJECT_PAPERS -->\n\nNo papers are linked to this project.\n\n"
        "<!-- END MANAGED:PROJECT_PAPERS -->\n\n## Notes\n",
        encoding="utf-8",
    )
    paper = store.note_path("doe2026")
    revision = store.revision(paper)
    proposal = operations.propose_curation(
        CurationProposalRequest(
            citekey="doe2026",
            expected_revision=revision,
            items=(
                CurationItem(
                    item_id="project-1",
                    kind="project-link",
                    value="weather-project",
                    rationale="Synthetic.",
                ),
            ),
        )
    )
    from research_kb.project_service import ProjectService

    real_index = ProjectService.index

    def editing_index(service: ProjectService, *, dry_run: bool = False) -> object:
        paper.write_text(paper.read_text(encoding="utf-8") + "\nExternal edit.\n", encoding="utf-8")
        return real_index(service, dry_run=dry_run)

    monkeypatch.setattr(ProjectService, "index", editing_index)
    with pytest.raises(ValidationError, match="revision conflict"):
        CurationApprovalService(operations).apply(
            ApprovedCurationRequest(
                proposal_id=proposal.proposal_id,
                decisions=(CurationDecision(item_id="project-1", decision="accepted"),),
                expected_revision=revision,
            )
        )
    assert paper.read_text(encoding="utf-8").endswith("External edit.\n")
    assert "[[doe2026]]" not in project.read_text(encoding="utf-8")


def test_all_rejected_decisions_atomically_resolve_proposal_state(tmp_path: Path) -> None:
    operations, store = _operations(tmp_path)
    revision = store.revision(store.note_path("doe2026"))
    proposal = operations.propose_curation(
        CurationProposalRequest(
            citekey="doe2026",
            expected_revision=revision,
            items=(
                CurationItem(
                    item_id="existing-1",
                    kind="existing-tag",
                    value="domain/weather",
                    rationale="Synthetic.",
                ),
            ),
        )
    )
    receipt = CurationApprovalService(operations).apply(
        ApprovedCurationRequest(
            proposal_id=proposal.proposal_id,
            decisions=(CurationDecision(item_id="existing-1", decision="rejected"),),
            expected_revision=revision,
        )
    )
    proposal_path = operations._proposals / f"{proposal.proposal_id}.json"
    state = json.loads(proposal_path.read_text(encoding="utf-8"))
    assert state["status"] == "applied"
    assert state["decisions"] == [{"decision": "rejected", "item_id": "existing-1"}]
    assert ".research/operations/curation-proposals" in " ".join(receipt.affected_paths)
